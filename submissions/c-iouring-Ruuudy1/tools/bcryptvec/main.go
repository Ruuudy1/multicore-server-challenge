// Command bcryptvec writes src/bcrypt_vectors.h: bcrypt hashes made by golang.org/x/crypto/bcrypt (what the
// reference server uses), for the C self-test. It also checks the hand-copied Openwall vectors against Go.
//
//	cd tools/bcryptvec && go run . > ../../src/bcrypt_vectors.h
package main

import (
	"fmt"
	"os"
	"strings"

	"golang.org/x/crypto/bcrypt"
)

func main() {
	openwall := [][2]string{
		{"U*U", "$2a$05$CCCCCCCCCCCCCCCCCCCCC.E5YPO9kmyuRGyh0XouQYb4YMJKvyOeW"},
		{"U*U*", "$2a$05$CCCCCCCCCCCCCCCCCCCCC.VGOzA784oUp/Z0DY336zx7pLYAy0lwK"},
		{"U*U*U", "$2a$05$XXXXXXXXXXXXXXXXXXXXXOAcXxm9kjPGEMsLznoKqmqw7tc8WCx4a"},
		{"0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789chars after 72 are ignored", "$2a$05$abcdefghijklmnopqrstuu5s2v8.iXieOjg/.AySBTTZIIVFJeBui"},
		{"", "$2a$05$CCCCCCCCCCCCCCCCCCCCC.7uG0VCzI2bS7j6ymqJi9CdcdxiRTWNy"},
		{"password123", "$2a$10$ZSfEoPvlcsj2XfvsSeK25em4NZ9Jm7ntGqXuLgQfHEeZPYB8899wq"},
	}
	for _, v := range openwall {
		if err := bcrypt.CompareHashAndPassword([]byte(v[1]), []byte(v[0])); err != nil {
			fmt.Fprintf(os.Stderr, "vector %q does not verify in Go: %v\n", v[0], err)
			os.Exit(1)
		}
	}
	pws := []string{"a", "conformance-pass-1", "pässwörd 日本", strings.Repeat("x", 71), strings.Repeat("y", 72),
		"tab\tquote\"backslash\\", "\xff\xfe\x80 high bytes", "password123"}
	fmt.Println("/* Generated by tools/bcryptvec (golang.org/x/crypto/bcrypt). Do not edit. */")
	for i, pw := range pws {
		cost := 4 + i%2
		h, err := bcrypt.GenerateFromPassword([]byte(pw), cost)
		if err != nil {
			panic(err)
		}
		fmt.Printf("    {%s, %q},\n", cString(pw), string(h))
	}
}

// cString quotes s as a C string literal, with octal escapes for anything outside printable ASCII.
func cString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			b.WriteByte(c)
		default:
			fmt.Fprintf(&b, "\\%03o", c)
		}
	}
	b.WriteByte('"')
	return b.String()
}
