#!/usr/bin/env python3
# Writes src/bf_init.h: Blowfish's initial P-array and S-boxes, the hexadecimal digits of pi's fractional part.
# Computed here (Machin's formula on big integers) instead of pasted, and checked against the published words.
import pathlib

WORDS = 18 + 4 * 256
DIGITS = WORDS * 8
GUARD = 16


def arctan_inv(x, one):
    total = term = one // x
    x2, n, sign = x * x, 1, -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign, n = -sign, n + 1
    return total


one = 16 ** (DIGITS + GUARD)
pi = (16 * arctan_inv(5, one) - 4 * arctan_inv(239, one)) // 16 ** GUARD
digits = format(pi, "x")[1:]  # drop the integer part 3
words = [int(digits[8 * i:8 * i + 8], 16) for i in range(WORDS)]
P, S = words[:18], [words[18 + 256 * k:18 + 256 * (k + 1)] for k in range(4)]
assert P[0] == 0x243F6A88 and P[1] == 0x85A308D3 and P[17] == 0x8979FB1B
assert S[0][0] == 0xD1310BA6 and S[0][255] == 0x6E85076A and S[3][255] == 0x3AC372E6

out = ["/* Generated by tools/gen_bf_init.py: Blowfish initial state, the hex digits of pi. Do not edit. */",
       "#pragma once", "#include <stdint.h>", "", "static const uint32_t BF_INIT_P[18] = {"]
out += ["    " + ", ".join(f"0x{w:08x}" for w in P[i:i + 6]) + "," for i in range(0, 18, 6)]
out += ["};", "", "static const uint32_t BF_INIT_S[4][256] = {"]
for box in S:
    out.append("    {")
    out += ["        " + ", ".join(f"0x{w:08x}" for w in box[i:i + 6]) + "," for i in range(0, 256, 6)]
    out.append("    },")
out += ["};", ""]
target = pathlib.Path(__file__).resolve().parent.parent / "src" / "bf_init.h"
target.write_text("\n".join(out), newline="\n")
print(f"wrote {target}")
