#!/usr/bin/env python3
# Writes src/sql_gen.h from tools/sqlcheck/statements.py, the source of truth for every statement: the C server
# prepares these exact strings with these parameter types. Change statements.py, pass check.py, then rerun this.
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "sqlcheck"))
import statements as S  # noqa: E402

LIST_SIG = "(bigint, int, int, text)"
KINDS = [("GLOBAL", "global"), ("TAG", "tag"), ("AUTHOR", "author"), ("FAVORITED", "favorited"), ("FEED", "feed")]

# C statement id -> (SQL, signature), in enum stmt_id order (conduit.h)
CATALOG = [
    ("U_GET", S.USERS["user_get"], S.USER_SIGNATURES["user_get"]),
    ("U_LOGIN", S.USERS["user_login"], S.USER_SIGNATURES["user_login"]),
    ("P_GET", S.USERS["profile"], S.USER_SIGNATURES["profile"]),
    ("T_LIST", S.WRITES["tags"], S.SIGNATURES["tags"]),
    ("A_GET", S.ARTICLE, "(bigint, bigint, text)"),
    ("A_GET_SLUG", S.ARTICLE_BY_SLUG, "(bigint, text)"),
    ("C_LIST", S.COMMENTS, "(bigint, bigint, text)"),
] + [(f"L1_{c}", S.V1[k], LIST_SIG) for c, k in KINDS] + [(f"L2_{c}", S.V2[k], LIST_SIG) for c, k in KINDS] + [
    (f"{prefix}_{c}", sqls[k], LIST_SIG) for prefix, sqls in (("L1D", S.V1D), ("L2C", S.V2C), ("L2T", S.V2T)) for c, k in KINDS
] + [
    ("A_GET_B", S.BATCHED["article_b"], S.BATCHED_SIGNATURES["article_b"]),
    ("C_LIST_B", S.BATCHED["comments_b"], S.BATCHED_SIGNATURES["comments_b"]),
    ("P_GET_B", S.BATCHED["profile_b"], S.BATCHED_SIGNATURES["profile_b"]),
    ("U_GET_B", S.BATCHED["user_get_b"], S.BATCHED_SIGNATURES["user_get_b"]),
] + [(f"LS_{c}", S.SHARED[k], S.SHARED_SIGNATURE) for c, k in KINDS if k in S.SHARED] + [
    ("U_REGISTER", S.USERS["user_register"], S.USER_SIGNATURES["user_register"]),
    ("U_UPDATE", S.USERS["user_update"], S.USER_SIGNATURES["user_update"]),
    ("P_FOLLOW", S.WRITES["follow"], S.SIGNATURES["follow"]),
    ("P_UNFOLLOW", S.WRITES["unfollow"], S.SIGNATURES["unfollow"]),
    ("C_ADD", S.WRITES["comment_add"], S.SIGNATURES["comment_add"]),
    ("C_DEL", S.WRITES["comment_del"], S.SIGNATURES["comment_del"]),
    ("F_ADD", S.WRITES["fav_add"], S.SIGNATURES["fav_add"]),
    ("F_DEL", S.WRITES["fav_del"], S.SIGNATURES["fav_del"]),
    ("A_ADD", S.WRITES["article_add"], S.SIGNATURES["article_add"]),
    ("A_PUT", S.WRITES["article_put"], S.SIGNATURES["article_put"]),
    ("A_DEL", S.WRITES["article_del"], S.SIGNATURES["article_del"]),
]
OIDS = {"bigint": "OID_INT8", "int": "OID_INT4", "text": "OID_TEXT", "text[]": "OID_TEXT_ARRAY", "bigint[]": "OID_INT8_ARRAY",
        "int[]": "OID_INT4_ARRAY"}


def c_literal(sql):
    out = []
    for line in sql.split("\n"):
        out.append('"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    out[-1] = out[-1][:-3] + '"'  # no newline after the last line
    return "\n    ".join(out)


def params(sig):
    names = [p.strip() for p in sig.strip("()").split(",") if p.strip()]
    return names, ", ".join(OIDS[p] for p in names) or "0"


lines = ["/* Generated by tools/gen_sql.py from tools/sqlcheck/statements.py. Do not edit. */", "#pragma once", ""]
for cid, sql, sig in CATALOG:
    names, oids = params(sig)
    lines.append(f"#define SQL_{cid} \\\n    {c_literal(sql).replace(chr(10), ' ' + chr(92) + chr(10))}")
    lines.append(f"#define SQL_{cid}_NPARAMS {len(names)}")
    lines.append(f"#define SQL_{cid}_PTYPES {{{oids}}}")
    lines.append("")
target = HERE.parent / "src" / "sql_gen.h"
target.write_text("\n".join(lines), newline="\n")
print(f"wrote {target} ({len(CATALOG)} statements)")
